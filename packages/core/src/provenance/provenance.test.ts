describe("facts", () => {
	it("refuse what the contract doesn't have, at its path", () => {
		const r = parseFacts({ ...run, temprature: "0.7" });
		expect(r.ok).toBe(false);
		const bad = parseFacts({
			...run,
			dataset: { ...run.dataset, sha256: "abc" },
		});
		expect(!bad.ok && bad.error[0]?.path).toBe("dataset.sha256");
		const two = parseFacts({
			...qualtrics,
			metadata: [{ name: "x", text: true, number: {} }],
		});
		expect(two.ok).toBe(false);
	});

	it("are checked against the instrument and themselves", () => {
		const f = facts({
			...run,
			weight: "seed",
			instrument: { ...run.instrument, workspace: "../" },
			dataset: {
				...run.dataset,
				present: [V("nope"), "urn:ddi:org.example:tenure:3"],
			},
			metadata: [...run.metadata, { name: "seed", text: true }],
		});
		expect(provenanceFindings(f, index).map((x) => [x.code, x.path])).toEqual([
			["provenance-facts", "metadata.1.name"],
			["provenance-weight", "weight"],
			["provenance-workspace", "instrument.workspace"],
			["provenance-unknown", "dataset.present.0"],
			["provenance-unknown", "dataset.present.1"],
		]);
	});

	it("say when the modes asked by and the mode variable's codes disagree", () => {
		const fewer = facts({ ...ingest, asked_by: ingest.asked_by.slice(0, 2) });
		expect(
			provenanceFindings(fewer, index).map((x) => [x.severity, x.path]),
		).toEqual([["error", "asked_by"]]);
		const none = facts({ ...ingest, metadata: ingest.metadata.slice(1) });
		expect(
			provenanceFindings(none, index).map((x) => [x.severity, x.path]),
		).toEqual([["warning", "asked_by"]]);
	});

	it("refuse a file whose digest differs; note one that isn't there", () => {
		const f = facts(run);
		const read = (p: string) =>
			p === "answers.csv"
				? SHA("0")
				: p === "traces.jsonl"
					? undefined
					: filesOf(f).find((x) => x.path === p)?.given;
		const found = digestFindings(
			filesOf(f).map((x) => ({ ...x, read: read(x.path) })),
		);
		expect(found.map((x) => [x.severity, x.path])).toEqual([
			["error", "dataset"],
			["info", "data.0"],
		]);
	});

	it("publish a JSON Schema of the input", () => {
		const s = provenanceFactsJsonSchema() as {
			required: string[];
			properties: Record<string, unknown>;
			additionalProperties: boolean;
		};
		expect(s.required).toEqual([
			"qretools_provenance",
			"name",
			"instrument",
			"asked_by",
			"answered_by",
			"dataset",
		]);
		expect(s.additionalProperties).toBe(false);
		expect(Object.keys(s.properties)).toContain("weight");
	});
});
