const facts = (json: unknown): ProvenanceFacts => {
	const r = parseFacts(json);
	if (!r.ok) throw new Error(JSON.stringify(r.error));
	return r.value;
};

type Doc = Record<string, Record<string, JsonObject>>;
const docOf = (f: ProvenanceFacts): Doc => provenanceDocument(f) as Doc;
const items = (d: Doc, type: string): JsonObject[] =>
	Object.values(d[type] ?? {});
const only = (d: Doc, type: string): JsonObject => {
	const all = items(d, type);
	expect(all).toHaveLength(1);
	return all[0] as JsonObject;
};
const keyOf = (r: JsonObject): string => (r.value as string[]).join(":");

/** Every reference in an item, at any depth: `{ $type, value }` objects. */
function refsIn(x: unknown): JsonObject[] {
	if (Array.isArray(x)) return x.flatMap(refsIn);
	if (typeof x !== "object" || x === null) return [];
	const o = x as JsonObject;
	if (typeof o.$type === "string" && Array.isArray(o.value)) return [o];
	return Object.values(o).flatMap(refsIn);
}

/**
 * Beyond the schema, which accepts undeclared properties: every reference into the provenance
 * resolves to an item of its type, every other names the instrument's DDI, and every item
 * is reached from the StudyUnit. Nothing is a Universe or a Sample.
 */
function structural(d: Doc) {
	expect(validator.ok && validator.value(d)).toEqual([]);
	const own = new Map<string, string>();
	for (const [type, bucket] of Object.entries(d))
		for (const key of Object.keys(bucket)) own.set(key, type);
	const outside = new Set(["Instrument", "QuestionItem", "Variable"]);
	for (const [, bucket] of Object.entries(d))
		for (const it of Object.values(bucket))
			for (const r of refsIn(it)) {
				const type = own.get(keyOf(r));
				if (type !== undefined) expect(r.$type).toBe(type);
				else {
					expect(outside.has(r.$type as string)).toBe(true);
					expect(index.byUrn.get(`urn:ddi:${keyOf(r)}`)?.type).toBe(r.$type);
				}
			}
	const [study] = Object.keys(d.StudyUnit ?? {});
	const seen = new Set<string>([study as string]);
	const queue = [study as string];
	while (queue.length > 0) {
		const key = queue.pop() as string;
		const type = own.get(key) as string;
		for (const r of refsIn(d[type]?.[key]))
			if (own.has(keyOf(r)) && !seen.has(keyOf(r))) {
				seen.add(keyOf(r));
				queue.push(keyOf(r));
			}
	}
	expect([...own.keys()].filter((k) => !seen.has(k))).toEqual([]);
	expect(d.Universe).toBeUndefined();
	expect(d.Sample).toBeUndefined();
	for (const p of items(d, "PhysicalInstance"))
		for (const fp of p.DataFingerprint as JsonObject[])
			expect(Object.keys(fp).sort()).toEqual([
				"AlgorithmSpecification",
				"DigitalFingerprintValue",
				"Type",
			]);
	// Variables the provenance defines are asked of no one.
	for (const v of items(d, "Variable"))
		expect(v.QuestionReference).toBeUndefined();
}

