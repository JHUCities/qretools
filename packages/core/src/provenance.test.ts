type Doc = Record<string, Record<string, JsonObject>>;
const made = (f: RunFolder): Doc => {
	const r = provenanceOf(f);
	if (!r.ok) throw new Error(JSON.stringify(r.error));
	return r.value as Doc;
};
const problems = (f: RunFolder) => {
	const r = provenanceOf(f);
	return r.ok ? [] : r.error;
};
const items = (d: Doc, type: string): JsonObject[] =>
	Object.values(d[type] ?? {});
const keyOf = (r: JsonObject): string => (r.value as string[]).join(":");

/** Every reference in an item, at any depth: `{ $type, value }` objects. */
function refsIn(x: unknown): JsonObject[] {
	if (Array.isArray(x)) return x.flatMap(refsIn);
	if (typeof x !== "object" || x === null) return [];
	const o = x as JsonObject;
	if (typeof o.$type === "string" && Array.isArray(o.value)) return [o];
	return Object.values(o).flatMap(refsIn);
}

/** The properties a root type declares, its own and Versionable's: the schema allows others unchecked. */
const declared = (type: string): Set<string> => {
	const defs = schema.$defs as Record<string, { properties?: object }>;
	return new Set([
		...Object.keys(defs[type]?.properties ?? {}),
		...Object.keys(defs.Versionable?.properties ?? {}),
	]);
};

/**
 * Beyond the schema: every reference resolves, to an item of the provenance or to one of
 * the instrument's DDI, of its type; every item is reached from the StudyUnit; every
 * property is one the schema declares; every file has its digest; no Universe or Sample.
 */
function structural(d: Doc) {
	expect(validator.ok && validator.value(d as DdiDocument)).toEqual([]);
	const own = new Map<string, string>();
	for (const [type, bucket] of Object.entries(d))
		for (const key of Object.keys(bucket)) own.set(key, type);
	for (const [type, bucket] of Object.entries(d))
		for (const it of Object.values(bucket)) {
			for (const key of Object.keys(it))
				expect(declared(type).has(key), `${type}.${key}`).toBe(true);
			for (const r of refsIn(it)) {
				const key = keyOf(r);
				const target = own.get(key) ?? index.byUrn.get(`urn:ddi:${key}`)?.type;
				expect(target, key).toBe(r.$type);
			}
		}
	const [study, ...more] = Object.keys(d.StudyUnit ?? {});
	expect(more).toEqual([]);
	const reached = new Set<string>();
	const visit = (key: string) => {
		const type = own.get(key);
		if (type === undefined || reached.has(key)) return;
		reached.add(key);
		for (const r of refsIn(d[type]?.[key])) visit(keyOf(r));
	};
	visit(study ?? "");
	expect([...own.keys()].filter((k) => !reached.has(k))).toEqual([]);
	expect(d.Universe).toBeUndefined();
	expect(JSON.stringify(d)).not.toMatch(/Universe|"Sample/);
	for (const p of items(d, "PhysicalInstance"))
		expect(JSON.stringify(p.DataFingerprint)).toMatch(/"[0-9a-f]{64}"/);
	// Every file of the folder, that is: a document the publisher's advice is quoted from isn't one.
	for (const m of items(d, "OtherMaterial").filter(
		(o) => (o.TypeOfMaterial as JsonObject).StringValue !== "weighting advice",
	))
		expect(JSON.stringify(m.UserAttributePair)).toMatch(
			/"sha256".*"[0-9a-f]{64}"/,
		);
}

describe("provenanceOf, a synthetic run", () => {
	it("says where its answers came from, as valid DDI reached from one StudyUnit", () => {
		const d = made(synthetic);
		structural(d);
		const [collection] = items(d, "DataCollection");
		expect(collection?.CollectionEvent).toMatchObject([
			{
				DataSource: [
					{
						SourceType: [{ StringValue: "Other", OtherValue: "synthetic" }],
					},
				],
				DataCollectionDate: {
					StartDate: { DateTime: "2026-11-12T09:00:00Z" },
					EndDate: { DateTime: "2026-11-12T10:00:00Z" },
				},
				ModeOfCollection: [
					{ TypeOfModeOfCollection: { StringValue: "Simulation" } },
				],
				InstrumentReference: [
					{
						$type: "Instrument",
						value: ["org.example", "instrument-wave1", "1"],
					},
				],
				UserAttributePair: [
					{ AttributeKey: { StringValue: "model" } },
					{ AttributeKey: { StringValue: "temperature" } },
				],
			},
		]);
		expect(items(d, "Methodology")[0]?.DataCollectionSoftware).toMatchObject([
			{ SoftwareVersion: "2026-10-01" },
		]);
		const groups = Object.fromEntries(
			items(d, "VariableGroup").map((g) => [
				g.ID,
				(g.VariableReference as JsonObject[]).map(keyOf),
			]),
		);
		const k = (n: string) => `org.example:instrument-wave1.var-${n}:1`;
		expect(groups).toEqual({
			"group-run-2026-11-12a.present": [k("mood"), k("tenure")],
			"group-run-2026-11-12a.removed-by-access": [k("ssn"), k("zip")],
		});
		const [answersFile] = items(d, "PhysicalInstance");
		expect(answersFile?.GrossFileStructure).toMatchObject({
			CaseQuantity: 2,
		});
		expect(items(d, "InformationClassification")).toMatchObject([
			{ LevelOfInformationClassification: { StringValue: "public" } },
		]);
		expect(items(d, "OtherMaterial").map((m) => m.TypeOfMaterial)).toEqual(
			["file", "instrument", "run facts", "file"].map((StringValue) => ({
				StringValue,
			})),
		);
	});

	it("never holds an answer or a respondent, and gives the same document for the same folder", () => {
		const text = JSON.stringify(made(synthetic));
		expect(text).not.toMatch(/VALUE-|RESP-/);
		const shuffled = {
			...synthetic,
			files: [...synthetic.files].reverse(),
			answers: [...answers].reverse(),
		};
		expect(JSON.stringify(made(shuffled))).toBe(text);
	});

	it("refuses a folder that disagrees with itself, saying where", () => {
		const run = synthetic.run as Record<string, unknown>;
		const at = (r: unknown, more: Partial<RunFolder> = {}) =>
			problems({ ...synthetic, run: r, ...more }).map(
				(p) => `${p.file}:${p.field ?? ""}`,
			);
		expect(at({ ...run, respondent: undefined })).toEqual([
			"run.json:respondent",
		]);
		expect(at({ ...run, asked_by: ["Interview"] })).toEqual([
			"run.json:asked_by",
		]);
		expect(at({ ...run, source: { title: "x" } })).toEqual(["run.json:source"]);
		expect(at({ ...run, runtime: undefined })).toEqual(["run.json:runtime"]);
		expect(at({ ...run, weather: "fine" })).toEqual(["run.json:"]);
		expect(at({ ...run, start: "12 Nov" })).toEqual(["run.json:start"]);
		expect(at({ ...run, start: "2026-11-12T11:00:00Z" })).toEqual([
			"run.json:start",
		]);
		// Answers above the level it says, or to a variable the DDI hasn't.
		expect(
			at(
				{ ...run, access: "public" },
				{
					answers: [
						...answers,
						{ respondent: "r", variable: v("zip"), value: "1" },
					],
				},
			),
		).toEqual(["answers.csv:access"]);
		expect(
			at(run, {
				answers: [{ respondent: "r", variable: "urn:ddi:x:y:1", value: "1" }],
			}),
		).toEqual(["answers.csv:"]);
		expect(at(run, { name: "run.1" })).toEqual(["run.1:"]);
		expect(at(run, { files: synthetic.files.slice(1, 2) })).toEqual([
			"ddi.json:",
		]);
		// Messages name files, fields and variables, never a value.
		expect(
			JSON.stringify(
				problems({ ...synthetic, run: { ...run, start: "VALUE-X" } }),
			),
		).not.toMatch(/VALUE-/);
	});
});

describe("provenanceOf, an ingest", () => {
	it("takes what the source says of itself, and names what the source doesn't hold", () => {
		const d = made(ingest);
		structural(d);
		const [collection] = items(d, "DataCollection");
		expect(collection?.CollectionEvent).toMatchObject([
			{
				DataSource: [
					{
						SourceType: [
							{
								StringValue: "Other",
								OtherValue: "generated by the survey platform",
							},
						],
					},
				],
				DataCollectionDate: { StartDate: { DateTime: platform.start } },
			},
		]);
		expect(items(d, "VariableGroup").map((g) => g.ID)).toEqual([
			"group-wave1-tests.present",
			"group-wave1-tests.not-in-source",
		]);
		expect(items(d, "PhysicalInstance").map((p) => p.ID)).toEqual([
			"file-wave1-tests.answers",
			"file-wave1-tests.source",
		]);
		expect(items(d, "OtherMaterial").map((m) => m.TypeOfMaterial)).toEqual([
			{ StringValue: "instrument" },
			{ StringValue: "column map" },
		]);
	});

	it("refuses run.json repeating what the source says, or declaring a synthetic run", () => {
		const fields = (run: unknown) =>
			problems({ ...ingest, run }).map((p) => p.field);
		expect(fields({ start: "2026-11-12" })).toEqual(["start"]);
		expect(fields({ respondent: "synthetic" })).toEqual(["respondent"]);
		expect(fields({ reported: {} })).toEqual(["reported"]);
	});

	it("needs a data file's facts declared, since no file says them", () => {
		const data: RunFolder = {
			...ingest,
			collection: {},
			map: {
				...ingest.map,
				path: "wave1-ddi-gss.columns.json",
				source: "gss",
			} as RunFolder["map"] & object,
		};
		expect(problems(data).map((p) => p.field)).toEqual([
			"asked_by",
			"answered_by",
		]);
		const d = made({
			...data,
			run: {
				asked_by: ["Interview.FaceToFace.CAPIorCAMI", "Interview.Telephone"],
				answered_by: "ResearchData.Published",
				source: {
					title: "Example Survey 2010, release 2",
					publisher: "Example Data Archive",
					url: "https://example.org/release2.zip",
				},
				start: "2010-03-01",
				end: "2010-08-31",
				access: "restricted",
			},
		});
		structural(d);
		expect(items(d, "DataCollection")[0]?.CollectionEvent).toMatchObject([
			{
				DataSource: [
					{
						SourceType: [{ StringValue: "ResearchData.Published" }],
						Origin: [{ OriginLocation: "https://example.org/release2.zip" }],
					},
				],
				ModeOfCollection: [{}, {}],
				DataCollectionDate: { StartDate: { Date: "2010-03-01" } },
			},
		]);
		// At restricted, only ssn is above; and ssn isn't in the source, so none is removed.
		expect(items(d, "VariableGroup").map((g) => g.ID)).toEqual([
			"group-wave1-tests.present",
			"group-wave1-tests.not-in-source",
		]);
	});
});

describe("provenanceOf, a data file with columns no respondent is asked", () => {
	const metadata: readonly MetadataColumn[] = [
		{
			column: "mode",
			label: "How the interview was done",
			role: "mode",
			unit: "Interviewer",
			codes: { "1": "In person", "2": "By phone" },
			modes: {
				"1": "Interview.FaceToFace.CAPIorCAMI",
				"2": "Interview.Telephone",
			},
		},
		{
			column: "phase",
			label: "Phase of the sample",
			role: "design",
			unit: { other: "survey organisation" },
			codes: { "1": "First phase", "2": "Second phase" },
		},
		{ column: "wtss", role: "weight", number: true, weight: true },
		{ column: "wtssnr", role: "weight", number: true, weight: true },
	];
	const m = (column: string) =>
		metadataUrn("urn:ddi:org.example:instrument-wave1:1", "survey", column);
	const data: RunFolder = {
		...ingest,
		collection: {},
		answers: [
			...answers,
			{ respondent: "RESP-ONE", variable: m("mode"), value: "2" },
			{ respondent: "RESP-ONE", variable: m("wtss"), value: "0.98765" },
			{ respondent: "RESP-TWO", variable: m("wtssnr"), value: "1.23456" },
		],
		files: [
			file("answers.csv", "a"),
			file("ddi.json", "d"),
			file("source.csv", "b"),
			file("wave1-ddi-survey.columns.json", "9"),
		],
		run: { answered_by: "ResearchData.Published" },
		map: {
			path: "wave1-ddi-survey.columns.json",
			source: "survey",
			reads: [v("tenure"), v("mood"), v("zip")],
			metadata,
			weighting: {
				advice: "ADVICE: use wtssnr for this year.",
				source: {
					title: "Example Survey codebook, release 2",
					publisher: "Example Data Archive",
					url: "https://example.org/codebook.pdf",
				},
				read: "2026-11-12",
			},
		},
	};

	it("owns their variables, lists each mode, and gives the publisher's advice once", () => {
		const d = made(data);
		structural(d);
		const [collection] = items(d, "DataCollection");
		expect(collection?.ProcessingEventSchemeReference).toHaveLength(1);
		expect(collection?.CollectionEvent).toMatchObject([
			{
				ModeOfCollection: [
					{
						TypeOfModeOfCollection: {
							StringValue: "Interview.FaceToFace.CAPIorCAMI",
						},
						UserAttributePair: [
							{
								AttributeKey: { StringValue: m("mode") },
								AttributeValue: { StringValue: "1" },
							},
						],
					},
					{ TypeOfModeOfCollection: { StringValue: "Interview.Telephone" } },
				],
			},
		]);
		const variables = Object.fromEntries(
			items(d, "Variable").map((x) => [x.URN, x]),
		);
		expect(Object.keys(variables)).toEqual(metadata.map((c) => m(c.column)));
		expect(variables[m("mode")]).toMatchObject({
			ID: "instrument-wave1-survey.mode",
			SourceUnit: { StringValue: "Interviewer" },
			VariableRepresentation: {
				VariableRole: { StringValue: "mode" },
				ValueRepresentation: { $type: "CodeDomain" },
			},
		});
		expect(variables[m("mode")]?.QuestionReference).toBeUndefined();
		expect(variables[m("mode")]?.IsWeight).toBeUndefined();
		const [weighting] = items(d, "Weighting");
		for (const w of ["wtss", "wtssnr"])
			expect(variables[m(w)]).toMatchObject({
				IsWeight: true,
				WeightingProcessReference: {
					value: ["org.example", weighting?.ID, "1"],
				},
				VariableRepresentation: {
					ValueRepresentation: { $type: "NumericDomain" },
				},
			});
		expect(items(d, "Weighting")).toHaveLength(1);
		expect(JSON.stringify(weighting?.UsageGuide)).toContain(
			'"Value":"ADVICE: use wtssnr for this year."',
		);
		expect(
			items(d, "OtherMaterial").find(
				(o) =>
					(o.TypeOfMaterial as JsonObject).StringValue === "weighting advice",
			),
		).toMatchObject({
			ExternalURLReference: ["https://example.org/codebook.pdf"],
			UserAttributePair: [{ AttributeValue: { StringValue: "2026-11-12" } }],
		});
		const groups = Object.fromEntries(
			items(d, "VariableGroup").map((g) => [
				g.ID,
				(g.VariableReference as JsonObject[]).map(keyOf),
			]),
		);
		const k = (c: string) => m(c).slice("urn:ddi:".length);
		expect(groups["group-wave1-tests.not-asked"]).toEqual(
			["mode", "phase", "wtss", "wtssnr"].map(k),
		);
		expect(groups["group-wave1-tests.present"]).toEqual(
			expect.arrayContaining(["mode", "wtss", "wtssnr"].map(k)),
		);
	});

	it("holds no value, gives the same document for the same folder, and the same variables in every run", () => {
		const text = JSON.stringify(made(data));
		expect(text).not.toMatch(/VALUE-|RESP-|0\.98765|1\.23456/);
		const shuffled = {
			...data,
			files: [...data.files].reverse(),
			answers: [...data.answers].reverse(),
		};
		expect(JSON.stringify(made(shuffled))).toBe(text);
		const other = made({ ...data, name: "another-run" });
		const strip = (d: Doc) =>
			items(d, "Variable").map(
				({ WeightingProcessReference: _, ...rest }) => rest,
			);
		expect(strip(other)).toEqual(strip(made(data)));
		expect(other.CodeList).toEqual(made(data).CodeList);
	});

	it("refuses run.json declaring the modes the map gives, and a variable the map doesn't", () => {
		expect(
			problems({ ...data, run: { answered_by: "x", asked_by: ["y"] } }).map(
				(p) => p.field,
			),
		).toEqual(["asked_by"]);
		expect(
			problems({
				...data,
				answers: [{ respondent: "r", variable: m("other"), value: "1" }],
			}).map((p) => p.file),
		).toEqual(["answers.csv"]);
	});
});
