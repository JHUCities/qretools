import { describe, expect, it } from "vitest";
import { exportCollection } from "./collection.ts";

const id = (o: object) => `"${JSON.stringify(o).replaceAll('"', '""')}"`;

/** An export's three header rows (as Qualtrics writes them) and its rows. */
const exported = (rows: readonly string[], zone = "Z") =>
	[
		"StartDate,EndDate,Status,ResponseId,DistributionChannel",
		"Start Date,End Date,Response Type,Response ID,Distribution Channel",
		[
			id({ ImportId: "startDate", timeZone: zone }),
			id({ ImportId: "endDate", timeZone: zone }),
			id({ ImportId: "status" }),
			id({ ImportId: "_recordId" }),
			id({ ImportId: "distributionChannel" }),
		].join(","),
		...rows,
		"",
	].join("\r\n");

const TESTS = [
	"2026-11-12 23:15:41,2026-11-12 23:15:50,2,R_1,test",
	"2026-11-12 23:14:02,2026-11-12 23:16:02,2,R_2,test",
];

describe("exportCollection", () => {
	it("dates the export by its first start and last end, and says test responses are the platform's", () => {
		expect(exportCollection(exported(TESTS))).toEqual({
			ok: true,
			value: {
				asked_by: ["Simulation"],
				answered_by: { other: "generated by the survey platform" },
				start: "2026-11-12T23:14:02Z",
				end: "2026-11-12T23:16:02Z",
				runtime: { name: "Qualtrics" },
			},
		});
		const web = exportCollection(
			exported(["2026-11-12 23:15:41,2026-11-12 23:15:50,0,R_1,anonymous"]),
		);
		expect(web.ok && web.value.asked_by).toEqual([
			"SelfAdministeredQuestionnaire.CAWI",
		]);
		expect(web.ok && web.value.answered_by).toBeUndefined();
	});

	it("refuses what it would have to guess", () => {
		const refused = (text: string) => {
			const r = exportCollection(text);
			return r.ok ? "" : r.error;
		};
		expect(
			refused(
				exported([
					...TESTS,
					"2026-11-12 23:15:41,2026-11-12 23:15:50,0,R_3,anonymous",
				]),
			),
		).toMatch(/differ in `status`/);
		expect(
			refused(
				exported(["2026-11-12 23:15:41,2026-11-12 23:15:50,1,R_1,preview"]),
			),
		).toMatch(/channel `preview`/);
		// Imported responses on a web link aren't the respondents' own answers on the web.
		expect(
			refused(
				exported(["2026-11-12 23:15:41,2026-11-12 23:15:50,4,R_1,anonymous"]),
			),
		).toMatch(/status `4`/);
		expect(refused(exported(TESTS, "America/New_York"))).toMatch(/time zone/);
		expect(
			refused(exported(["11/12/2026,2026-11-12 23:15:50,2,R_1,test"])),
		).toMatch(/^Line 4: `startDate`/);
		expect(refused(exported([]))).toMatch(/no responses/);
	});
});
