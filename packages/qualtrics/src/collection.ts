/**
 * What a Qualtrics response export says of its own collection, for a dataset's
 * provenance (`provenanceOf` in the core). Pure: text in, a value out.
 */
import {
	type Collection,
	err,
	ok,
	parseCsv,
	type Result,
} from "@qretools/core";

/** The channels whose respondents answered on the web themselves. */
// shortcut: only Qualtrics' anonymous link and email invitation; add a channel when an export shows it.
const WEB = new Set(["anonymous", "email"]);

/** `Status` as "Export values" writes it: a response (IP Address), and a test response. */
const RESPONSE = "0";
const TEST = "2";

/** A Qualtrics timestamp as exported: `2026-11-12 23:15:41`. */
const TIMESTAMP = /^\d{4}-\d\d-\d\d \d\d:\d\d:\d\d$/;

/** A time zone DDI can write: UTC or an offset. */
const ZONE = /^(Z|[+-]\d\d:\d\d)$/;

/**
 * The earliest `StartDate` and the latest `EndDate`, in the zone the third header row
 * names, and how the respondents were asked and who answered, from
 * `DistributionChannel`: test responses (`test` on every row) are generated by the
 * platform. Columns are found by their ImportId. Refused, never guessed: rows that differ
 * in `Status` or `DistributionChannel` (a dataset holds one kind of respondent), a
 * channel not known here, a zone that isn't `Z` or an offset, a time in another form, or
 * no responses. A message names a column or a line, never a response.
 */
export function exportCollection(text: string): Result<Collection, string> {
	const [, , ids, ...rows] = parseCsv(text).rows;
	if (ids === undefined || rows.length === 0)
		return err(
			"The export has no responses, so it says nothing of when or how they were collected.",
		);
	const header = ids.cells.map((cell): Record<string, unknown> => {
		try {
			const j: unknown = JSON.parse(cell);
			return typeof j === "object" && j !== null
				? (j as Record<string, unknown>)
				: {};
		} catch {
			return {};
		}
	});
	const column = (
		importId: string,
	): Result<
		{ readonly cells: readonly string[]; readonly zone: unknown },
		string
	> => {
		const i = header.findIndex((h) => h.ImportId === importId);
		return i < 0
			? err(`The export has no column with ImportId \`${importId}\`.`)
			: ok({
					cells: rows.map((r) => r.cells[i] ?? ""),
					zone: header[i]?.timeZone,
				});
	};
	const one = (importId: string): Result<string, string> => {
		const c = column(importId);
		if (!c.ok) return c;
		return new Set(c.value.cells).size === 1
			? ok(c.value.cells[0] ?? "")
			: err(
					`The rows differ in \`${importId}\`: a dataset holds one kind of respondent, so export each kind apart.`,
				);
	};
	const time = (
		importId: string,
		pick: "first" | "last",
	): Result<string, string> => {
		const c = column(importId);
		if (!c.ok) return c;
		const { cells, zone } = c.value;
		if (typeof zone !== "string" || !ZONE.test(zone))
			return err(
				`The time zone of \`${importId}\` (third header row) isn't \`Z\` or an offset such as \`-05:00\`: export the responses in UTC.`,
			);
		const bad = cells.findIndex((x) => !TIMESTAMP.test(x));
		if (bad >= 0)
			return err(
				`Line ${rows[bad]?.line}: \`${importId}\` isn't a time as Qualtrics exports one (2026-11-12 23:15:41).`,
			);
		// One form and one zone, so the text sorts as the time does.
		const sorted = [...cells].sort();
		const t = (pick === "first" ? sorted[0] : sorted.at(-1)) ?? "";
		return ok(`${t.replace(" ", "T")}${zone}`);
	};
	const status = one("status");
	if (!status.ok) return status;
	const channel = one("distributionChannel");
	if (!channel.ok) return channel;
	const start = time("startDate", "first");
	if (!start.ok) return start;
	const end = time("endDate", "last");
	if (!end.ok) return end;
	const how: Collection | undefined =
		channel.value === "test" && status.value === TEST
			? {
					asked_by: ["Simulation"],
					answered_by: { other: "generated by the survey platform" },
				}
			: WEB.has(channel.value) && status.value === RESPONSE
				? { asked_by: ["SelfAdministeredQuestionnaire.CAWI"] }
				: undefined;
	if (how === undefined)
		return err(
			`Responses of status \`${status.value}\` on the distribution channel \`${channel.value}\` aren't ones QREtools can describe yet: it describes test responses (\`2\`, \`test\`) and responses on a web link or by email (\`0\`, \`anonymous\` or \`email\`).`,
		);
	return ok({
		...how,
		start: start.value,
		end: end.value,
		runtime: { name: "Qualtrics" },
	});
}
